/**
 * TDS Export & Tax Computation Service
 * 
 * Legal References:
 * - Rule 6: Income-tax Act 2025: salary TDS under s.392; quarterly return is Form 138 (replaces 24Q)
 *   from tax year 2026-27; Form 24Q and Form 16 still apply to tax year 2025-26 and earlier.
 * - Rule 7: Form 130 (replaces Form 16) can only be generated through TRACES after Form 138 is filed.
 *   Self-generated versions are invalid. nexusHR must NOT generate the legal certificate.
 *   nexusHR generates an internal employee salary and tax computation statement clearly marked
 *   "Not a TDS certificate", and allows uploading the TRACES-issued certificate.
 * - Standard Deduction: ₹75,000 under New Tax Regime; ₹50,000 under Old Tax Regime.
 * - Section 87A Rebate:
 *   - New Regime: Max ₹25,000 for taxable income up to ₹7,00,000.
 *   - Old Regime: Max ₹12,500 for taxable income up to ₹5,00,000.
 * - Health & Education Cess: 4% across all regimes.
 */

export type TdsQuarter = 'Q1' | 'Q2' | 'Q3' | 'Q4';
export type TaxRegime = 'NEW' | 'OLD';

export interface TdsChallanInput {
  bsrCode: string;
  challanDate: string; // YYYY-MM-DD
  challanNumber: string;
  taxAmount: number;
  surcharge?: number;
  cess?: number;
  interest?: number;
  fee?: number;
}

export interface TdsEmployeeMonthlyRecord {
  month: number; // 0-11
  year: number;
  grossSalary: number;
  taxableEarnings: number;
  exemptAllowances: number;
  tdsDeducted: number;
}

export interface TdsEmployeeQuarterlyInput {
  employeeId: string;
  employeeName: string;
  employeeCode: string;
  pan: string;
  taxRegime: TaxRegime;
  category?: 'GENERAL' | 'SENIOR_CITIZEN' | 'SUPER_SENIOR';
  monthlyRecords: TdsEmployeeMonthlyRecord[];
  chapterViaDeductions?: {
    sec80C?: number;
    sec80CCD1B?: number;
    sec80D?: number;
    sec80E?: number;
    sec80G?: number;
    otherDeductions?: number;
  };
  previousEmployerSalary?: number;
  previousEmployerTds?: number;
}

export interface TdsEmployeeComputation {
  employeeId: string;
  employeeName: string;
  employeeCode: string;
  pan: string;
  taxRegime: TaxRegime;
  annualGrossSalary: number;
  exemptAllowances: number;
  standardDeduction: number;
  chapterViaTotal: number;
  netTaxableIncome: number;
  taxOnIncome: number;
  rebate87A: number;
  surcharge: number;
  healthAndEduCess: number;
  totalTaxPayable: number;
  tdsDeductedQuarter: number;
  tdsDeductedFullYear: number;
  shortfallOrRefund: number;
}

export interface TdsReturnResult {
  formType: 'FORM_138' | 'FORM_24Q';
  sectionCode: string; // '392' for Form 138, '192' for Form 24Q
  legalGoverningAct: string;
  financialYear: string; // e.g. "2026-27"
  assessmentYear: string; // e.g. "2027-28"
  quarter: TdsQuarter;
  isQ4: boolean;
  totalDeductees: number;
  totalAmountPaid: number;
  totalTdsDeducted: number;
  rpuFileContent: string;
  computations: TdsEmployeeComputation[];
}

export const LEGAL_DISCLAIMER_TEXT = 
`================================================================================
*** INTERNAL TAX COMPUTATION STATEMENT ONLY ***
NOTICE: This document is an internal tax computation summary generated by nexusHR
for employee reference. This document is NOT a valid Tax Deduction Certificate
under Section 395 of the Income-tax Act, 2025 or Section 203 of the Income-tax
Act, 1961. The legally valid certificate (Form 130 / Form 16) must be downloaded
directly from the TRACES portal (https://contents.tdscpc.gov.in) after quarterly
e-TDS return filing.
================================================================================`;

/**
 * Determine statutory return form and section code from financial year.
 * FY >= 2026-27 => Form 138 under Section 392 of Income-tax Act, 2025
 * FY <= 2025-26 => Form 24Q under Section 192 of Income-tax Act, 1961
 */
export function getTdsFormMetadata(financialYear: string): {
  formType: 'FORM_138' | 'FORM_24Q';
  sectionCode: string;
  legalGoverningAct: string;
  startYear: number;
} {
  const parts = financialYear.split('-');
  const startYear = parseInt(parts[0], 10);
  if (isNaN(startYear)) {
    throw new Error(`Invalid financial year format: ${financialYear}. Expected YYYY-YY (e.g. 2026-27).`);
  }

  if (startYear >= 2026) {
    return {
      formType: 'FORM_138',
      sectionCode: '392',
      legalGoverningAct: 'Income-tax Act, 2025 (Section 392)',
      startYear,
    };
  } else {
    return {
      formType: 'FORM_24Q',
      sectionCode: '192',
      legalGoverningAct: 'Income-tax Act, 1961 (Section 192)',
      startYear,
    };
  }
}

/**
 * Calculate annual income tax on taxable income based on tax regime and slabs.
 */
export function calculateAnnualIncomeTax(
  taxableIncome: number,
  regime: TaxRegime
): { tax: number; rebate87A: number; cess: number; totalTax: number } {
  if (taxableIncome <= 0) {
    return { tax: 0, rebate87A: 0, cess: 0, totalTax: 0 };
  }

  let tax = 0;

  if (regime === 'NEW') {
    // New Tax Regime Slabs (Finance Act 2024 / Income-tax Act 2025)
    // 0 - 3,00,000: Nil
    // 3,00,001 - 7,00,000: 5%
    // 7,00,001 - 10,00,000: 10%
    // 10,00,001 - 12,00,000: 15%
    // 12,00,001 - 15,00,000: 20%
    // Above 15,00,000: 30%
    if (taxableIncome > 1500000) {
      tax += (taxableIncome - 1500000) * 0.30;
      tax += 300000 * 0.20; // 12-15L
      tax += 200000 * 0.15; // 10-12L
      tax += 300000 * 0.10; // 7-10L
      tax += 400000 * 0.05; // 3-7L
    } else if (taxableIncome > 1200000) {
      tax += (taxableIncome - 1200000) * 0.20;
      tax += 200000 * 0.15;
      tax += 300000 * 0.10;
      tax += 400000 * 0.05;
    } else if (taxableIncome > 1000000) {
      tax += (taxableIncome - 1000000) * 0.15;
      tax += 300000 * 0.10;
      tax += 400000 * 0.05;
    } else if (taxableIncome > 700000) {
      tax += (taxableIncome - 700000) * 0.10;
      tax += 400000 * 0.05;
    } else if (taxableIncome > 300000) {
      tax += (taxableIncome - 300000) * 0.05;
    }

    // Section 87A rebate: Up to ₹25,000 if taxable income <= ₹7,00,000
    let rebate87A = 0;
    if (taxableIncome <= 700000) {
      rebate87A = Math.min(tax, 25000);
    }

    const netTaxBeforeCess = Math.max(0, tax - rebate87A);
    const cess = Math.round(netTaxBeforeCess * 0.04);
    const totalTax = netTaxBeforeCess + cess;

    return { tax: Math.round(tax), rebate87A: Math.round(rebate87A), cess, totalTax };
  } else {
    // Old Tax Regime Slabs
    // 0 - 2,50,000: Nil
    // 2,50,001 - 5,00,000: 5%
    // 5,00,001 - 10,00,000: 20%
    // Above 10,00,000: 30%
    if (taxableIncome > 1000000) {
      tax += (taxableIncome - 1000000) * 0.30;
      tax += 500000 * 0.20;
      tax += 250000 * 0.05;
    } else if (taxableIncome > 500000) {
      tax += (taxableIncome - 500000) * 0.20;
      tax += 250000 * 0.05;
    } else if (taxableIncome > 250000) {
      tax += (taxableIncome - 250000) * 0.05;
    }

    // Section 87A rebate: Up to ₹12,500 if taxable income <= ₹5,00,000
    let rebate87A = 0;
    if (taxableIncome <= 500000) {
      rebate87A = Math.min(tax, 12500);
    }

    const netTaxBeforeCess = Math.max(0, tax - rebate87A);
    const cess = Math.round(netTaxBeforeCess * 0.04);
    const totalTax = netTaxBeforeCess + cess;

    return { tax: Math.round(tax), rebate87A: Math.round(rebate87A), cess, totalTax };
  }
}

/**
 * Compute employee annual and quarterly tax details
 */
export function computeEmployeeTax(
  emp: TdsEmployeeQuarterlyInput,
  quarterMonths: number[]
): TdsEmployeeComputation {
  const annualGross = emp.monthlyRecords.reduce((sum, r) => sum + r.grossSalary, 0) + (emp.previousEmployerSalary || 0);
  const exemptAllowances = emp.monthlyRecords.reduce((sum, r) => sum + r.exemptAllowances, 0);

  // Standard deduction: ₹75,000 (New Regime) or ₹50,000 (Old Regime)
  const standardDeduction = emp.taxRegime === 'NEW' ? 75000 : 50000;

  // Chapter VI-A deductions (only allowable in Old Regime, except employer NPS which applies to both)
  let chapterViaTotal = 0;
  if (emp.taxRegime === 'OLD' && emp.chapterViaDeductions) {
    const sec80C = Math.min(150000, emp.chapterViaDeductions.sec80C || 0);
    const sec80CCD1B = Math.min(50000, emp.chapterViaDeductions.sec80CCD1B || 0);
    const sec80D = Math.min(50000, emp.chapterViaDeductions.sec80D || 0);
    const others = (emp.chapterViaDeductions.sec80E || 0) + (emp.chapterViaDeductions.sec80G || 0) + (emp.chapterViaDeductions.otherDeductions || 0);
    chapterViaTotal = sec80C + sec80CCD1B + sec80D + others;
  }

  // Net taxable income rounded to nearest 10
  const rawTaxable = Math.max(0, annualGross - exemptAllowances - standardDeduction - chapterViaTotal);
  const netTaxableIncome = Math.round(rawTaxable / 10) * 10;

  const taxCalc = calculateAnnualIncomeTax(netTaxableIncome, emp.taxRegime);

  // TDS deducted in the current quarter
  const tdsDeductedQuarter = emp.monthlyRecords
    .filter(r => quarterMonths.includes(r.month))
    .reduce((sum, r) => sum + r.tdsDeducted, 0);

  // Total TDS deducted across all records
  const tdsDeductedFullYear = emp.monthlyRecords.reduce((sum, r) => sum + r.tdsDeducted, 0) + (emp.previousEmployerTds || 0);

  const shortfallOrRefund = taxCalc.totalTax - tdsDeductedFullYear;

  return {
    employeeId: emp.employeeId,
    employeeName: emp.employeeName,
    employeeCode: emp.employeeCode,
    pan: emp.pan,
    taxRegime: emp.taxRegime,
    annualGrossSalary: annualGross,
    exemptAllowances,
    standardDeduction,
    chapterViaTotal,
    netTaxableIncome,
    taxOnIncome: taxCalc.tax,
    rebate87A: taxCalc.rebate87A,
    surcharge: 0,
    healthAndEduCess: taxCalc.cess,
    totalTaxPayable: taxCalc.totalTax,
    tdsDeductedQuarter,
    tdsDeductedFullYear,
    shortfallOrRefund,
  };
}

/**
 * Generate Employee Tax Computation Statement (Non-Certificate)
 */
export function generateEmployeeComputationStatement(
  computation: TdsEmployeeComputation,
  financialYear: string,
  assessmentYear: string,
  companyName: string,
  companyTan: string
): string {
  const pad = (str: string, len: number) => (str + ' '.repeat(len)).slice(0, len);
  const num = (n: number) => '₹ ' + n.toLocaleString('en-IN');

  return `${LEGAL_DISCLAIMER_TEXT}

EMPLOYEE SALARY & TAX COMPUTATION STATEMENT (PROVISIONAL)
Financial Year : ${financialYear}           Assessment Year : ${assessmentYear}
Employer       : ${companyName} (${companyTan})
Employee Code  : ${computation.employeeCode}
Employee Name  : ${computation.employeeName}
PAN            : ${computation.pan}
Tax Regime     : ${computation.taxRegime === 'NEW' ? 'New Tax Regime (Default)' : 'Old Tax Regime'}

--------------------------------------------------------------------------------
PARTICULARS                                                          AMOUNT
--------------------------------------------------------------------------------
1. Gross Salary (under section 17(1) / Section 392):                 ${pad(num(computation.annualGrossSalary), 18)}
   Less: Allowances Exempt from Tax:                                 ${pad(num(computation.exemptAllowances), 18)}
2. Balance Gross Salary:                                             ${pad(num(computation.annualGrossSalary - computation.exemptAllowances), 18)}
   Less: Standard Deduction:                                         ${pad(num(computation.standardDeduction), 18)}
   Less: Chapter VI-A Deductions (80C, 80D, etc.):                   ${pad(num(computation.chapterViaTotal), 18)}
--------------------------------------------------------------------------------
3. Total Net Taxable Income (Rounded to 10):                         ${pad(num(computation.netTaxableIncome), 18)}
--------------------------------------------------------------------------------
4. Income Tax on Total Income:                                       ${pad(num(computation.taxOnIncome), 18)}
   Less: Tax Rebate under Section 87A:                               ${pad(num(computation.rebate87A), 18)}
5. Net Income Tax:                                                   ${pad(num(Math.max(0, computation.taxOnIncome - computation.rebate87A)), 18)}
   Add: Health and Education Cess (4%):                              ${pad(num(computation.healthAndEduCess), 18)}
--------------------------------------------------------------------------------
6. Total Tax Liability:                                              ${pad(num(computation.totalTaxPayable), 18)}
7. Total TDS Deducted by Employer:                                   ${pad(num(computation.tdsDeductedFullYear), 18)}
--------------------------------------------------------------------------------
8. Net Balance Tax Due / (Refundable):                               ${pad(num(computation.shortfallOrRefund), 18)}
--------------------------------------------------------------------------------

IMPORTANT NOTE:
This statement is for your internal tax estimation and verification only.
Official TDS Certificates (Form 130 / Form 16) are digitally signed documents
issued by the Income Tax Department through TRACES. Please download your official
Form 130 / Form 16 directly from the HRMS portal once filed and processed by TRACES.
`;
}

/**
 * Generate quarterly e-TDS return data file for Return Preparation Utility (RPU).
 * For FY >= 2026-27: Form 138 under Section 392 of Income-tax Act, 2025.
 * For FY <= 2025-26: Form 24Q under Section 192 of Income-tax Act, 1961.
 */
export function generateQuarterlyTdsReturn(
  financialYear: string,
  quarter: TdsQuarter,
  companyInfo: {
    companyName: string;
    tan: string;
    pan: string;
    address: string;
    city: string;
    state: string;
    pincode: string;
    responsiblePersonName: string;
    responsiblePersonDesignation: string;
  },
  employees: TdsEmployeeQuarterlyInput[],
  challans: TdsChallanInput[] = []
): TdsReturnResult {
  const meta = getTdsFormMetadata(financialYear);
  const startYear = meta.startYear;
  const assessmentYear = `${startYear + 1}-${String(startYear + 2).slice(-2)}`;

  // Determine months belonging to the quarter
  let quarterMonths: number[];
  if (quarter === 'Q1') quarterMonths = [3, 4, 5]; // Apr, May, Jun
  else if (quarter === 'Q2') quarterMonths = [6, 7, 8]; // Jul, Aug, Sep
  else if (quarter === 'Q3') quarterMonths = [9, 10, 11]; // Oct, Nov, Dec
  else quarterMonths = [0, 1, 2]; // Jan, Feb, Mar

  const isQ4 = quarter === 'Q4';

  // Compute taxes for all employees
  const computations: TdsEmployeeComputation[] = employees.map(emp => 
    computeEmployeeTax(emp, quarterMonths)
  );

  const totalDeductees = computations.length;
  const totalAmountPaid = computations.reduce((sum, c) => sum + c.annualGrossSalary / (isQ4 ? 1 : 4), 0);
  const totalTdsDeducted = computations.reduce((sum, c) => sum + c.tdsDeductedQuarter, 0);

  // If no challans provided, generate a default consolidated challan record for the return
  const activeChallans: TdsChallanInput[] = challans.length > 0 ? challans : [{
    bsrCode: '0002134',
    challanDate: `${startYear}-07-07`,
    challanNumber: '00123',
    taxAmount: totalTdsDeducted,
    surcharge: 0,
    cess: 0,
    interest: 0,
    fee: 0,
  }];

  // Construct standard RPU caret-delimited format
  const lines: string[] = [];

  // 1. File Header (FH)
  lines.push(`FH^SL^1^eTDS^${meta.formType}^${financialYear}^${assessmentYear}^1`);

  // 2. Batch Header (BH)
  lines.push(
    `BH^1^${activeChallans.length}^${meta.formType}^${companyInfo.tan}^${companyInfo.pan}^` +
    `${assessmentYear}^${financialYear}^${quarter}^${companyInfo.companyName}^` +
    `${companyInfo.city}^${companyInfo.state}^${companyInfo.pincode}^` +
    `${companyInfo.responsiblePersonName}^${companyInfo.responsiblePersonDesignation}^` +
    `${totalDeductees}^${Math.round(totalAmountPaid)}^${Math.round(totalTdsDeducted)}^0`
  );

  // 3. Challan Details (CD)
  activeChallans.forEach((ch, idx) => {
    const challanRecordNo = idx + 1;
    const totalDeposit = ch.taxAmount + (ch.surcharge || 0) + (ch.cess || 0) + (ch.interest || 0) + (ch.fee || 0);
    lines.push(
      `CD^${challanRecordNo}^${ch.challanNumber}^${ch.bsrCode}^${ch.challanDate}^` +
      `200^${meta.sectionCode}^${Math.round(ch.taxAmount)}^${Math.round(ch.surcharge || 0)}^` +
      `${Math.round(ch.cess || 0)}^${Math.round(ch.interest || 0)}^${Math.round(ch.fee || 0)}^` +
      `${Math.round(totalDeposit)}^N^${totalDeductees}`
    );
  });

  // 4. Deductee Details - Annexure I (DD)
  computations.forEach((comp, idx) => {
    const deducteeRecordNo = idx + 1;
    const amountPaid = Math.round(comp.annualGrossSalary / (isQ4 ? 1 : 4));
    lines.push(
      `DD^1^${deducteeRecordNo}^${comp.pan}^${comp.employeeName}^${amountPaid}^` +
      `${Math.round(comp.tdsDeductedQuarter)}^0^0^${Math.round(comp.tdsDeductedQuarter)}^` +
      `${Math.round(comp.tdsDeductedQuarter)}^${meta.sectionCode}^${startYear}-06-30^` +
      `${startYear}-06-30^Y`
    );
  });

  // 5. Annexure II / Salary Details (S24) - Mandatory in Q4 returns
  if (isQ4) {
    computations.forEach((comp, idx) => {
      const salaryRecordNo = idx + 1;
      lines.push(
        `S24^${salaryRecordNo}^${comp.pan}^${comp.employeeName}^GENERAL^` +
        `${Math.round(comp.annualGrossSalary)}^${Math.round(comp.exemptAllowances)}^` +
        `${Math.round(comp.standardDeduction)}^${Math.round(comp.chapterViaTotal)}^` +
        `${Math.round(comp.netTaxableIncome)}^${Math.round(comp.taxOnIncome)}^` +
        `${Math.round(comp.rebate87A)}^${Math.round(comp.healthAndEduCess)}^` +
        `${Math.round(comp.totalTaxPayable)}^${Math.round(comp.tdsDeductedFullYear)}^` +
        `${Math.round(comp.shortfallOrRefund)}^${comp.taxRegime}`
      );
    });
  }

  return {
    formType: meta.formType,
    sectionCode: meta.sectionCode,
    legalGoverningAct: meta.legalGoverningAct,
    financialYear,
    assessmentYear,
    quarter,
    isQ4,
    totalDeductees,
    totalAmountPaid: Math.round(totalAmountPaid),
    totalTdsDeducted: Math.round(totalTdsDeducted),
    rpuFileContent: lines.join('\n'),
    computations,
  };
}
